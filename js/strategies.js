/** Ожидаемый счёт стороны color в семействе: свои победы + половина ничьих. */
function expectedScoreForColor(stats, color) {
    return (color === "w" ? stats.w : stats.b) + stats.d / 2;
}

/**
 * Самое глубокое (длинный префикс) семейство для текущей партии.
 * history — массив SAN-ходов. Возвращает запись семейства или null.
 */
function findStrategy(history) {
    let best = null;
    let bestLen = 0;
    for (const fam of STRATEGY_FAMILIES) {
        for (const prefix of fam.prefixes) {
            const toks = prefix.split(" ");
            if (toks.length > history.length || toks.length <= bestLen) continue;
            if (toks.every((t, i) => history[i] === t)) {
                best = fam;
                bestLen = toks.length;
            }
        }
    }
    return best;
}
