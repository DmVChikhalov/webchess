/**
 * Ищет самую глубокую запись базы, соответствующую началу партии.
 * history — массив SAN-ходов. Возвращает {entry, depth} или null.
 */
function findOpening(history) {
    let best = null;
    for (let depth = history.length; depth >= 1; depth--) {
        const key = history.slice(0, depth).join(" ");
        if (OPENINGS[key]) {
            best = { entry: OPENINGS[key], depth };
            break;
        }
    }
    return best;
}

/** Запись точно для текущего числа ходов (последний ход есть в базе). */
function openingForLastMove(history) {
    const key = history.join(" ");
    return OPENINGS[key] || null;
}
