/** Случайная тренировка; исключить id (чтобы новый дебют не повторял только что пройденный). */
function pickDrill(excludeId) {
    const pool = DRILLS.filter((d) => d.id !== excludeId);
    return pool[Math.floor(Math.random() * pool.length)];
}
